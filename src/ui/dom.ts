type Attrs = Record<string, string | number | boolean | null | undefined | ((e: Event) => void)>;
type Child = Node | string | null | undefined | false;

/** Creates an element: h('button.rb-small', { title: 'Cut', onclick }, icon, 'Cut'). */
export function h<K extends keyof HTMLElementTagNameMap>(
  spec: K | `${K}.${string}` | `${K}#${string}`,
  attrs: Attrs = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const [tagAndId, ...classes] = spec.split('.');
  const [tag, id] = tagAndId.split('#');
  const el = document.createElement(tag as K);
  if (id) el.id = id;
  if (classes.length) el.className = classes.join(' ');
  for (const [key, value] of Object.entries(attrs)) {
    if (value === null || value === undefined || value === false) continue;
    if (typeof value === 'function') {
      el.addEventListener(key.replace(/^on/, ''), value as EventListener);
    } else if (key === 'class') {
      el.className += (el.className ? ' ' : '') + String(value);
    } else if (key in el && key !== 'list' && key !== 'role' && !key.startsWith('aria-') && !key.startsWith('data-')) {
      (el as unknown as Record<string, unknown>)[key] = value;
    } else {
      el.setAttribute(key, value === true ? '' : String(value));
    }
  }
  for (const c of children) if (c !== null && c !== undefined && c !== false) el.append(c);
  return el;
}

/** Inserts SVG (generated by us, never by the user) into a <span>. */
export function svg(markup: string, className = 'icon'): HTMLSpanElement {
  const span = document.createElement('span');
  span.className = className;
  span.innerHTML = markup;
  return span;
}

/** Label with the access key letter underlined: "Save &as" → Save as with the a underlined. */
export function accessLabel(text: string): { node: DocumentFragment; key: string | null } {
  const frag = document.createDocumentFragment();
  const i = text.indexOf('&');
  if (i < 0 || i === text.length - 1) {
    frag.append(text);
    return { node: frag, key: null };
  }
  const key = text[i + 1];
  frag.append(text.slice(0, i));
  const u = document.createElement('u');
  u.className = 'ak';
  u.textContent = key;
  frag.append(u, text.slice(i + 2));
  return { node: frag, key: key.toLowerCase() };
}

export function plainLabel(text: string): string {
  return text.replace('&', '');
}

/** Places a floating element next to a point or rectangle without overflowing the window. */
export function placePopup(el: HTMLElement, x: number, y: number, alt?: { x: number; y: number }): void {
  el.style.left = '0px';
  el.style.top = '0px';
  const r = el.getBoundingClientRect();
  const vw = window.innerWidth;
  const vh = window.innerHeight;
  let left = x;
  let top = y;
  if (left + r.width > vw - 2) left = alt ? alt.x - r.width : vw - r.width - 2;
  if (top + r.height > vh - 2) top = alt ? Math.max(2, alt.y - r.height) : Math.max(2, vh - r.height - 2);
  el.style.left = `${Math.max(2, left)}px`;
  el.style.top = `${Math.max(2, top)}px`;
}
